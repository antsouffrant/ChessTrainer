const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const js = fs.readFileSync('static/trainer.js','utf8');
const page = fs.readFileSync('templates/player.html','utf8');
const client = fs.readFileSync('static/player.js','utf8');
const base = fs.readFileSync('templates/base.html','utf8');
const app = fs.readFileSync('app.py','utf8');
const settings = fs.readFileSync('app_settings.py','utf8');
assert.match(base,/url_for\('player_view'\)/);
assert.match(page,/name="job_id"/);
assert.match(page,/name="primary_motif_key"/);
assert.match(page,/name="position_id"/);
assert.match(page,/player-attempt-export/);
assert.match(page,/player-session-export/);
assert.match(client,/\/api\/player\/summary/);
assert.match(app, /@app\.get\('\/api\/player\/summary'\)/);
assert.match(settings,/max_puzzle_solve_seconds/);
assert.match(js,/active_seconds_delta:activeSecondsDelta/);
assert.match(js,/if \(!solved\) learningClockStart\(p\.id\)/);
// Evaluate the actual stopwatch helpers with simulated foreground time.
const name = 'learningClockCanRun|learningClockPause|learningClockResume|learningClockStart|learningClockSnapshot|learningClockCommit';
const definitions = [...js.matchAll(new RegExp(`function (${name})\\([^\\n]*\\) \\{[\\s\\S]*?\\n\\}`, 'g'))].map(x=>x[0]);
assert.equal(definitions.length,6);
let clock=0;
const sandbox = {document:{visibilityState:'visible',hasFocus:()=>true},performance:{now:()=>clock}};
vm.createContext(sandbox);
vm.runInContext(`let learningTrackingEnabled=true,learningClockPositionId=null,learningClockElapsedMs=0,learningClockSince=null; ${definitions.join('\n')} this.time={start:learningClockStart,pause:learningClockPause,resume:learningClockResume,snapshot:learningClockSnapshot,commit:learningClockCommit}`,sandbox);
sandbox.time.start(37);
clock=12000;
assert.equal(sandbox.time.snapshot(),12);
clock=22000;
sandbox.time.resume();
clock=27000;
sandbox.time.pause();
assert.equal(sandbox.time.snapshot(),17);
sandbox.time.commit();
clock=29000;
assert.equal(sandbox.time.snapshot(),2);
sandbox.document.visibilityState='hidden';
sandbox.time.resume();
clock=45000;
assert.equal(sandbox.time.snapshot(),2, 'Hidden-tab idle time should not be counted');
console.log('Player view navigation, event tracking and foreground timer contracts passed');
