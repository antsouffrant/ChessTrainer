const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const src = fs.readFileSync('static/trainer.js', 'utf8');
const start = src.indexOf('function escapeCoachHtml');
const end = src.indexOf('// The server stores each historical reference', start);
assert(start >= 0 && end > start);
const html = vm.runInNewContext(src.slice(start, end) + `\ncoachMessageHtml({role:'assistant',content:'Explore a tactic',structured_json:JSON.stringify({kind:'brilliant_reference',brilliant_reference:{title:'Review Nf3',url:'/trainer/7?position=53'}})})`);
assert.match(html, /Coach · From your games/);
assert.match(html, /href="\/trainer\/7\?position=53"/);
assert.match(html, /Review Nf3/);
const unsafe = vm.runInNewContext(src.slice(start, end) + `\ncoachMessageHtml({role:'assistant',content:'<script>unsafe</script>',structured_json:JSON.stringify({kind:'brilliant_reference',brilliant_reference:{title:'Bad',url:'javascript:alert(1)'}})})`);
assert(!unsafe.includes('href="javascript:'));
assert(unsafe.includes('&lt;script&gt;unsafe&lt;/script&gt;'));
console.log('Proactive review message rendering and safe links: passed');
