"""Stage 5 — pure, non-mutating coaching validation.

Provides checks that can be applied to structured evidence and generated
continuations. Validation is report-only in this structural release; moving
validation into the live path will be a separate, tested behavioral change.
"""
from dataclasses import dataclass

@dataclass(frozen=True)
class ValidationResult:
    valid: bool
    problems: tuple[str, ...]


def validate_evidence(evidence, *, expected_root_uci=None) -> ValidationResult:
    """Reject unsupported evidence, mismatched roots and discontinuous PVs.

    The BoardEvidence generated by stage 1 includes the legal replay prefix;
    a truncated line cannot support claims about any omitted later ply.
    """
    problems = []
    if not evidence.legal:
        problems.append('illegal_root')
    if expected_root_uci is not None and evidence.root_uci != expected_root_uci:
        problems.append('wrong_root')
    if evidence.continuation_uci and evidence.continuation_uci[0] != evidence.root_uci:
        problems.append('wrong_pv_root')
    if evidence.truncated:
        problems.append('truncated_pv')
    return ValidationResult(not problems, tuple(problems))


def validate_message_identity(*, expected_position_id, actual_position_id,
                              expected_root_uci, actual_root_uci,
                              expected_version, actual_version) -> ValidationResult:
    """Check message provenance before associating feedback with a version."""
    problems = []
    if str(expected_position_id) != str(actual_position_id):
        problems.append('wrong_position')
    if expected_root_uci != actual_root_uci:
        problems.append('wrong_root')
    if expected_version != actual_version:
        problems.append('wrong_model_version')
    return ValidationResult(not problems, tuple(problems))
